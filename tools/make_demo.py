"""Generate small reserved-address PCAPs; never captures or transmits network traffic."""
import json
from pathlib import Path
import sys

from scapy.all import DNS, DNSQR, DNSRR, Ether, ICMP, IP, Raw, TCP, UDP, wrpcap

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))


def captures():
    packets=[]
    epoch=1700000100
    def emit(offset,layer):
        raw=Ether(src='02:00:00:00:00:20',dst='02:00:00:00:00:10')/IP(src='192.0.2.20',dst='198.51.100.10')/layer
        raw.time=epoch+offset
        packets.append(raw)
    def http(offset,port,request):
        emit(offset,TCP(sport=port,dport=8080,flags='S',seq=100))
        # Requests intentionally span TCP segments, exercising our reassembler.
        emit(offset+.1,TCP(sport=port,dport=8080,flags='PA',seq=101)/Raw(request[:20]))
        emit(offset+.2,TCP(sport=port,dport=8080,flags='PA',seq=121)/Raw(request[20:]))
    for index in range(3):
        http(index,20000+index,b'GET / HTTP/1.1\r\nHost: lab.example\r\n\r\n')
    emit(3,UDP(sport=30000,dport=53)/DNS(id=1,qd=DNSQR(qname='normal.lab.example')))
    benign=list(packets)
    emit(10,ICMP())
    for index in range(15):
        emit(11+index*.02,TCP(sport=40000+index,dport=10000+index,flags='S',seq=index))
    http(12,22000,b'GET /../../etc/passwd HTTP/1.1\r\nHost: lab.example\r\n\r\n')
    body=b'username=fictional&password=not-a-real-secret'
    http(13,22001,b'POST /login HTTP/1.1\r\nHost: lab.example\r\nContent-Type: application/x-www-form-urlencoded\r\nContent-Length: '+str(len(body)).encode()+b'\r\n\r\n'+body)
    emit(14,UDP(sport=30001,dport=53)/DNS(id=2,qd=DNSQR(qname='blocked.lab.example')))
    return benign,packets


def main():
    directory=ROOT/'examples';directory.mkdir(exist_ok=True)
    benign,mixed=captures()
    wrpcap(str(directory/'benign.pcap'),benign)
    wrpcap(str(directory/'scenarios.pcap'),mixed)
    (directory/'README.md').write_text('# Synthetic captures\n\nGenerated by `python tools/make_demo.py`. Addresses use documentation-only ranges. No real traffic is included. `benign.pcap` contains normal HTTP/DNS requests; `scenarios.pcap` adds all five custom-rule scenarios. ML scores depend on the frozen trained artifact and are evaluated separately from rule correctness. No packets are transmitted by generation or analysis.\n')
    print(json.dumps({'benign_packets':len(benign),'scenario_packets':len(mixed)}))


if __name__=='__main__':main()
